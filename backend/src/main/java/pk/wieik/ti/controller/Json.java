package pk.wieik.ti.controller;

import jakarta.servlet.http.HttpServletResponse;

import java.io.IOException;

/** Wysyłanie odpowiedzi JSON. Wszystkie kontrolery zwracają wyłącznie {@code application/json}. */
final class Json {
    private Json() {}

    static void send(HttpServletResponse response, int status, String json) throws IOException {
        response.setStatus(status);
        response.setContentType("application/json");
        response.setCharacterEncoding("UTF-8");
        response.getWriter().write(json);
    }

    /** Tekst jako literał JSON w cudzysłowie, z escapowaniem znaków specjalnych. */
    static String quote(String value) {
        if (value == null) {
            return "null";
        }
        StringBuilder out = new StringBuilder(value.length() + 2).append('"');
        for (char c : value.toCharArray()) {
            switch (c) {
                case '"' -> out.append("\\\"");
                case '\\' -> out.append("\\\\");
                case '\n' -> out.append("\\n");
                case '\r' -> out.append("\\r");
                case '\t' -> out.append("\\t");
                default -> {
                    if (c < 0x20) {
                        out.append(String.format("\\u%04x", (int) c));
                    } else {
                        out.append(c);
                    }
                }
            }
        }
        return out.append('"').toString();
    }
}
